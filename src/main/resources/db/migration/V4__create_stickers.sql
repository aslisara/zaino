CREATE TABLE stickers (
                          id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          user_id    BIGINT       NOT NULL,
                          country    VARCHAR(100) NOT NULL,
                          city       VARCHAR(100),
                          visited_on DATE,
                          note       VARCHAR(500),
                          created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX idx_stickers_user ON stickers (user_id);

-- Aynı kullanıcı aynı ülke/şehir için iki kez sticker alamasın
CREATE UNIQUE INDEX uq_stickers_user_place
    ON stickers (user_id, lower(country), lower(coalesce(city, '')));